    private void showPaymentMethodSheet() {
        View content = getLayoutInflater().inflate(R.layout.sheet_payment_method, null);
        LinearLayout options = content.findViewById(R.id.layoutPaymentOptions);
        BottomSheetDialog sheet = createBottomSheet(content);
        String selectedCode = viewModel.getPaymentMethod();

        for (String code : PaymentMethodUi.codes()) {
            View row = getLayoutInflater().inflate(R.layout.item_sheet_payment_method, options, false);
            ((ImageView) row.findViewById(R.id.imagePaymentIcon)).setImageResource(PaymentMethodUi.iconOf(code));
            ((TextView) row.findViewById(R.id.textPaymentLabel)).setText(PaymentMethodUi.labelOf(code));
            row.findViewById(R.id.imagePaymentCheck)
                    .setVisibility(code.equals(selectedCode) ? View.VISIBLE : View.INVISIBLE);
            row.setOnClickListener(v -> {
                viewModel.setPaymentMethod(code);
                showPaymentMethod(code);
                sheet.dismiss();
            });
            options.addView(row);
        }
        sheet.show();
    }

    private BottomSheetDialog createBottomSheet(View content) {
        dismissActiveSheet();
        BottomSheetDialog sheet = new BottomSheetDialog(requireContext());
        sheet.setContentView(content);
        sheet.getBehavior().setSkipCollapsed(true);
        sheet.getBehavior().setState(BottomSheetBehavior.STATE_EXPANDED);
        activeSheet = sheet;
        return sheet;
    }

    private void dismissActiveSheet() {
        if (activeSheet != null) {
            activeSheet.dismiss();
            activeSheet = null;
        }
    }

    private void setupNoteField() {
        //Ô ghi chú là ô cuối của form: bàn phím hiện nút Xong. textMultiLine làm bàn phím bỏ qua imeOptions,
        //nên đặt lại kiểu nhập thô (không multiline) — ô vẫn hiển thị nhiều dòng nhờ XML
        editNote.setRawInputType(InputType.TYPE_CLASS_TEXT | InputType.TYPE_TEXT_FLAG_CAP_SENTENCES);
        editNote.setOnEditorActionListener((v, actionId, event) -> {
            if (actionId == EditorInfo.IME_ACTION_DONE) {
                hideKeyboard();
                return true;
            }
            return false;
        });
        editNote.addTextChangedListener(new TextWatcher() {
            @Override
            public void beforeTextChanged(CharSequence s, int start, int count, int after) {
            }

            @Override
            public void onTextChanged(CharSequence s, int start, int before, int count) {
            }

            @Override
            public void afterTextChanged(Editable s) {
                editNote.post(editNote::requestLayout);
                if (suppressNoteWatcher) {
                    return;
                }
                String note = s.toString();
                viewModel.setNote(note);
                Result<Void> validation = viewModel.validateNoteField(note);
                inputLayoutNote.setError(validation instanceof Result.Error ? ((Result.Error<Void>) validation).message : null);
            }
        });
    }

