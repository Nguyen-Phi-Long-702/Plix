    //sourceNote: null = chưa có/không phải giao dịch tự tạo; chuỗi rỗng = mẫu định kỳ không có ghi chú
    private void renderAutoGeneratedBanner(@Nullable String sourceNote) {
        if (sourceNote == null) {
            layoutAutoGeneratedBanner.setVisibility(View.GONE);
            return;
        }
        SpannableStringBuilder text = new SpannableStringBuilder("Giao dịch này được Plix tự động tạo từ giao dịch định kỳ");
        if (!sourceNote.isEmpty()) {
            text.append(" \"");
            int start = text.length();
            text.append(sourceNote);
            text.setSpan(new StyleSpan(Typeface.BOLD), start, text.length(), Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
            text.append("\"");
        }
        text.append(". Sửa hoặc xoá chỉ ảnh hưởng riêng kỳ này — các kỳ khác không thay đổi.");
        textAutoGenerated.setText(text);
        layoutAutoGeneratedBanner.setVisibility(View.VISIBLE);
    }

