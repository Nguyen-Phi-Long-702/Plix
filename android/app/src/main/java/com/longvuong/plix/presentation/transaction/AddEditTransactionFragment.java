    private void renderCategorySuggestionState(UiState<CategorySuggestionUiModel> state) {
        if (state instanceof UiState.Loading) {
            showSuggestionCard(R.drawable.bg_ai_box, R.drawable.ic_sparkle, R.color.primary, R.color.text_secondary);
            textSuggestionTitle.setVisibility(View.GONE);
            textSuggestionDetail.setText("Đang phân tích ghi chú để gợi ý danh mục...");
            layoutSuggestionActions.setVisibility(View.GONE);
            chipRetryCategorize.setVisibility(View.GONE);
        } else if (state instanceof UiState.Success) {
            CategorySuggestionUiModel suggestion = ((UiState.Success<CategorySuggestionUiModel>) state).data;
            textSuggestionTitle.setVisibility(View.VISIBLE);
            chipRetryCategorize.setVisibility(View.GONE);
            if (suggestion.lowConfidence) {
                showSuggestionCard(R.drawable.bg_ai_box_low, R.drawable.ic_warning,
                        R.color.budget_progress_warning, R.color.warn_strong);
                textSuggestionTitle.setText(suggestion.label);
                textSuggestionDetail.setText("Vui lòng kiểm tra lại danh mục.");
                layoutSuggestionActions.setVisibility(View.GONE);
            } else {
                showSuggestionCard(R.drawable.bg_ai_box, R.drawable.ic_sparkle, R.color.primary, R.color.text_secondary);
                SpannableStringBuilder title = new SpannableStringBuilder("Gợi ý: ");
                int start = title.length();
                title.append(suggestion.categoryName);
                title.setSpan(new ForegroundColorSpan(ContextCompat.getColor(requireContext(), R.color.primary_dark)),
                        start, title.length(), Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
                textSuggestionTitle.setText(title);
                textSuggestionDetail.setText("Độ tin cậy tương đối: " + suggestion.confidencePercent + "%");
                layoutSuggestionActions.setVisibility(View.VISIBLE);
            }
        } else if (state instanceof UiState.Error) {
            showSuggestionCard(R.drawable.bg_ai_box_error, R.drawable.ic_warning,
                    R.color.text_tertiary, R.color.text_secondary);
            textSuggestionTitle.setVisibility(View.GONE);
            textSuggestionDetail.setText(((UiState.Error<CategorySuggestionUiModel>) state).message);
            layoutSuggestionActions.setVisibility(View.GONE);
            chipRetryCategorize.setVisibility(View.VISIBLE);
        } else {
            layoutCategorySuggestion.setVisibility(View.GONE); //Bao gồm cả offline: ViewModel trả Empty -> ẩn hẳn khối gợi ý
        }
    }

    private void showSuggestionCard(@DrawableRes int backgroundRes, @DrawableRes int iconRes,
                                    @ColorRes int iconColorRes, @ColorRes int detailColorRes) {
        layoutCategorySuggestion.setBackgroundResource(backgroundRes);
        layoutCategorySuggestion.setVisibility(View.VISIBLE);
        imageSuggestionIcon.setImageResource(iconRes);
        imageSuggestionIcon.setImageTintList(ColorStateList.valueOf(ContextCompat.getColor(requireContext(), iconColorRes)));
        textSuggestionDetail.setTextColor(ContextCompat.getColor(requireContext(), detailColorRes));
    }

    private void hideKeyboard() {
        InputMethodManager imm = (InputMethodManager) requireContext().getSystemService(Context.INPUT_METHOD_SERVICE);
        View currentFocus = requireActivity().getCurrentFocus();
        if (imm != null && currentFocus != null) {
            imm.hideSoftInputFromWindow(currentFocus.getWindowToken(), 0);
        }
    }
