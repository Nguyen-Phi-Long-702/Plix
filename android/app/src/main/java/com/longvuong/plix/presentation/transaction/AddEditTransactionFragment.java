    private void setupTypeToggle() {
        toggleType.addOnButtonCheckedListener((group, checkedId, isChecked) -> {
            if (!isChecked) {
                return;
            }
            boolean income = checkedId == R.id.btnIncome;
            String newType = income ? "income" : "expense";
            if (!newType.equals(viewModel.getType())) {
                viewModel.setType(newType); //bỏ qua khi chỉ đang đồng bộ giao diện với loại đã có, tránh xoá danh mục đã chọn khi danh sách chưa nạp xong
            }
            editAmount.setTextColor(ContextCompat.getColor(requireContext(),
                    income ? R.color.color_income : R.color.color_expense));
        });
    }

    private void setupAmountField() {
        editAmount.setOnEditorActionListener((v, actionId, event) -> {
            if (actionId == EditorInfo.IME_ACTION_DONE) {
                hideKeyboard();
                return true;
            }
            return false;
        });
        editAmount.addTextChangedListener(new TextWatcher() {
            @Override
            public void beforeTextChanged(CharSequence s, int start, int count, int after) {
            }

            @Override
            public void onTextChanged(CharSequence s, int start, int before, int count) {
            }

            @Override
            public void afterTextChanged(Editable s) {
                if (suppressAmountWatcher) {
                    return;
                }
                long amount = parseAmount(s.toString());
                String formatted = s.length() == 0 ? "" : amountFormat.format(amount);
                if (!formatted.equals(s.toString())) {
                    suppressAmountWatcher = true;
                    s.replace(0, s.length(), formatted);
                    suppressAmountWatcher = false;
                    editAmount.setSelection(s.length());
                    amount = parseAmount(s.toString()); //bộ lọc maxLength có thể cắt bớt chuỗi vừa định dạng (khi dán số rất dài)
                }
                viewModel.setAmount(amount);
                Result<Void> validation = viewModel.validateAmountField(amount);
                inputLayoutAmount.setError(validation instanceof Result.Error
                        ? ((Result.Error<Void>) validation).message : null);
            }
        });
    }

    private long parseAmount(String raw) {
        String digitsOnly = raw.replaceAll("[^0-9]", "");
        if (digitsOnly.isEmpty()) {
            return 0L;
        }
        try {
            return Long.parseLong(digitsOnly);
        } catch (NumberFormatException e) {
            return 0L;
        }
    }

    private void setupCategoryChips() {
        chipGroupCategory.setOnCheckedStateChangeListener((group, checkedIds) -> {
            if (suppressCategoryChipListener) {
                return;
            }
            viewModel.setCategoryId(checkedIds.isEmpty() ? null : categoryIdByChipId.get(checkedIds.get(0)));
        });
    }

    private void populateCategoryChips(List<CategoryEntity> categories) {
        suppressCategoryChipListener = true;
        chipGroupCategory.removeAllViews();
        categoryIdByChipId.clear();
        if (categories != null) {
            String selectedCategoryId = viewModel.getCategoryId();
            for (CategoryEntity category : categories) {
                Chip chip = (Chip) getLayoutInflater().inflate(R.layout.chip_filter_category, chipGroupCategory, false);
                chip.setId(View.generateViewId());
                chip.setText(category.name);
                chip.setChipIcon(ContextCompat.getDrawable(requireContext(), CategoryIconMapper.iconFor(category.id)));
                chipGroupCategory.addView(chip);
                categoryIdByChipId.put(chip.getId(), category.id);
                if (category.id.equals(selectedCategoryId)) {
                    chip.setChecked(true);
                }
            }
        }
        suppressCategoryChipListener = false;
    }

    //Chọn lại chip theo categoryId hiện có trong ViewModel (dùng sau khi áp dụng gợi ý AI)
    private void refreshCategoryChipSelection() {
        String selectedCategoryId = viewModel.getCategoryId();
        suppressCategoryChipListener = true;
        chipGroupCategory.clearCheck();
        for (Map.Entry<Integer, String> entry : categoryIdByChipId.entrySet()) {
            if (entry.getValue().equals(selectedCategoryId)) {
                chipGroupCategory.check(entry.getKey());
                break;
            }
        }
        suppressCategoryChipListener = false;
    }

    private void setupDateField() {
        editDate.setOnClickListener(v -> openDatePicker());
        inputLayoutDate.setEndIconOnClickListener(v -> openDatePicker());
    }

    private void openDatePicker() {
        ZonedDateTime current = Instant.ofEpochMilli(viewModel.getOccurredAt())
                .atZone(ZoneId.systemDefault());

        DatePickerDialog dialog = new DatePickerDialog(requireContext(), R.style.Theme_Plix_DatePicker, (picker, year, month, dayOfMonth) -> {
            LocalDate newDate = LocalDate.of(year, month + 1, dayOfMonth);
            LocalTime existingTime = current.toLocalTime();
            long newOccurredAt = ZonedDateTime.of(newDate, existingTime, ZoneId.systemDefault())
                    .toInstant().toEpochMilli();

            Result<Void> validation = viewModel.validateOccurredAtField(newOccurredAt);
            if (validation instanceof Result.Error) {
                inputLayoutDate.setError(((Result.Error<Void>) validation).message);
            } else {
                inputLayoutDate.setError(null);
                viewModel.setOccurredAt(newOccurredAt);
                editDate.setText(formatDate(newOccurredAt));
            }
        },
                current.getYear(), current.getMonthValue() - 1, current.getDayOfMonth());
        dialog.show();
    }

    private String formatDate(long epochMs) {
        return Instant.ofEpochMilli(epochMs)
                .atZone(ZoneId.systemDefault())
                .format(DateTimeFormatter.ofPattern("dd/MM/yyyy"));
    }

